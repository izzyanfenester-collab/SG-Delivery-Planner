const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync('pwa/delivery-core.js','utf8')+';globalThis.D=DeliveryCore;',ctx);
const D=ctx.D,now='2026-10-12T02:00:00.000Z';
const a={id:'a',status:'Pending',legSeconds:300,legKm:2,arrival:'2026-10-12T01:30:00.000Z'};
const b={id:'b',status:'Pending',legSeconds:0,legKm:0};
assert.equal(D.counts([a,b]).pending,2);
const delivered=D.update(a,'Delivered',now);
assert.equal(delivered.deliveredAt,now);
assert.throws(()=>D.update(delivered,'Hold',now,'Other','note'));
assert.throws(()=>D.update(b,'Hold',now,'Other',''));
const hold=D.update(b,'Hold',now,'Other','Reschedule after 6');
assert.equal(hold.holdNote,'Reschedule after 6');
assert.equal(D.counts([delivered,hold]).successRate,50);
assert.equal(D.nextUnreviewed([delivered,b],0),1);
assert.equal(D.nextUnreviewed([delivered,hold],0),-1);
const eta=D.recalculate([delivered,b],'2026-10-12T06:00:00.000Z',8);
assert.ok(Date.parse(eta.stops[1].etaArrival)>=Date.parse(now));
assert.equal(eta.stops[0].deliveredAt,now);
console.log('Delivery state tests passed');
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({});vm.runInContext(fs.readFileSync('pwa/orders.js','utf8')+';globalThis.OrdersCoreTest=OrdersCore;',context);
const c=context.OrdersCoreTest;
assert.equal(c.normalizePhone('9798 3272'),'+6597983272');
assert.equal(c.normalizePhone('https://wa.me/+6597983272'),'+6597983272');
assert.equal(c.normalizePhone('0123456789'),'');
const order=(name,code)=>'🔥 ORDER TELEKUNG\n👤 Nama: '+name+"\n📍 Alamat:\nBlk 189B Marsiling Road\n#11-960 S'pore "+code+'\n📱 WhatsApp:\nhttps://wa.me/+6597983272\n💰 Total: $65 (COD)\n🛒 Item: PINK BELACAN';
let n=0;const next=()=>String(++n);
const a=c.parse(order('A','732189')+'\n'+order('B','732189'),next);
assert.equal(a.stops.length,2);assert.equal(a.stops[0].postal,'732189');assert.equal(a.stops[1].postal,'732189');
assert.notEqual(a.stops[0].id,a.stops[1].id);
assert.equal(a.stops[0].amount,'65');assert.equal(a.stops[0].payment,'Cash On Delivery');
assert.equal(a.stops[0].phone,'+6597983272');
assert.equal(a.stops[0].name,'A');assert.equal(a.stops[1].name,'B');
const b=c.parse('[31/07, 11:21 pm] Eyra: '+order('A','732189')+'\n[31/07, 11:22 pm] Eyra: '+order('B','650202'),next);
assert.equal(b.stops.length,2);assert.equal(b.stops[1].postal,'650202');
const d=c.parse('650202\n732189\n650202',next);assert.equal(d.stops.length,2);assert.equal(d.duplicates,1);
const f=c.parse('👤 Nama: X\n📍 Alamat: nowhere\n💰 Total: $3',next);assert.equal(f.failed,1);
const repeated=c.parse(order('A','732189')+'\n'+order('A','732189'),next);
assert.equal(repeated.stops.length,1);assert.equal(repeated.duplicates,1);
console.log('WhatsApp parser parity tests passed');